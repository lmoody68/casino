"""AI Dealer — "Ace", the house host who reacts to your play.

Two tiers, so the app is great with zero setup and better with AI available:

* **Rule-based (default):** a hand-written line bank keyed by game event. Instant,
  offline, no dependencies, with anti-repeat so Ace doesn't say the same thing twice.

* **Optional LLM upgrade:** if you set the env var ``CASINO_DEALER_MODEL`` to a local
  Ollama model name (e.g. ``llama3.2:1b``), Ace's line is regenerated by that model
  a moment later for extra personality. It runs on a background thread, times out
  fast, and silently keeps the rule-based line if Ollama isn't running. The AI is a
  *bonus layer* — never a requirement.

Ace speaks in the first person (no third-person pronouns), so the character never
assumes a gender. If the voice module is enabled, each final line is also spoken.
"""
