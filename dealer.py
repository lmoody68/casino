_TIMEOUT = 8          # seconds to wait on the local model before giving up


def _model():
    return os.environ.get("CASINO_DEALER_MODEL", "").strip()


def llm_enabled():
    return bool(_model())


def _pick(event, ctx, avoid=None):
    bank = LINES.get(event) or LINES["greeting"]
    choices = [ln for ln in bank if ln != avoid] or bank
    line = random.choice(choices)
    try:
        return line.format(**ctx)
    except (KeyError, IndexError):
        return line


def _llm_line(event, ctx):
    """Ask a local Ollama model for one short in-character line. Returns None on any failure."""
    facts = ", ".join(f"{k}={v}" for k, v in ctx.items()) or "none"
    prompt = (
        f"You are {NAME}, a smooth, upbeat casino dealer at Mac Land Casino. "
        f"The player just had this event in {ctx.get('game', 'a game')}: '{event}'. "
        f"Details: {facts}. "
        "Say ONE short, punchy line to the player (max 12 words). "
        "First person only. No emoji. No quotes. Keep it fun and encouraging."
    )
    body = json.dumps({
        "model": _model(),
        "prompt": prompt,
        "stream": False,
        "options": {"num_predict": 40, "temperature": 0.9},
    }).encode()
    try:
        req = urllib.request.Request("http://localhost:11434/api/generate", data=body,
                                     headers={"Content-Type": "application/json"})
        with urllib.request.urlopen(req, timeout=_TIMEOUT) as resp:
            out = json.loads(resp.read()).get("response", "").strip()
        out = out.splitlines()[0].strip().strip('"').strip() if out else ""
        return out[:120] if out else None
    except Exception:
        return None


class DealerBox:
    """A compact dealer strip (name + line + voice toggle) plus a ``react`` method.
    Mount one per game window and call ``react(event, **ctx)`` on game events."""

    def __init__(self, parent, win, felt=theme.NIGHT):
        self.win = win
        self._last = None
        self._seq = 0

        self.frame = tk.Frame(parent, bg=felt)
        top = tk.Frame(self.frame, bg=felt)
        top.pack(fill="x")
        tk.Label(top, text=f"🎙  {NAME.upper()}", font=("Georgia", 10, "bold"),
                 bg=felt, fg=theme.GOLD).pack(side="left", padx=(2, 8))
        self.voice_btn = tk.Button(top, text="🔈  Voice: off", font=("Segoe UI", 8, "bold"),
                                   bg=theme.NIGHT2, fg=theme.GOLD, activebackground="#232b4d",
                                   relief="flat", bd=0, padx=8, pady=2, cursor="hand2",
                                   command=self._toggle_voice)
        self.voice_btn.pack(side="right", padx=2)
        if not voice.available():
            self.voice_btn.config(state="disabled", text="🔈  Voice: n/a")

        self.line = tk.Label(self.frame, text="", font=("Segoe UI", 10, "italic"),
                             bg=felt, fg=theme.IVORY, wraplength=460, justify="left", anchor="w")
        self.line.pack(fill="x", pady=(1, 0))

    def pack(self, **kw):
        self.frame.pack(**kw)
        return self

    def _toggle_voice(self):
        on = voice.toggle()
        self.voice_btn.config(text="🔊  Voice: on" if on else "🔈  Voice: off")
        if on and self._last:
            voice.speak(self._last)

    def react(self, event, **ctx):
        """Show (and optionally speak) a dealer line for a game event."""
        line = _pick(event, ctx, avoid=self._last)
        self._last = line
        self.line.config(text=line)
        voice.speak(line)

        if llm_enabled():                             # optional richer line, off the UI thread
            self._seq += 1
            seq = self._seq
            threading.Thread(target=self._upgrade, args=(event, ctx, seq), daemon=True).start()

    def _upgrade(self, event, ctx, seq):
        line = _llm_line(event, ctx)
        if not line:
            return

        def apply():
            if seq != self._seq:                      # a newer event already superseded this one
                return
            self._last = line
            self.line.config(text=line)
            voice.speak(line)
        self.win.after(0, apply)
